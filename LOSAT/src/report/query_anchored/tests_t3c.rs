fn sequence(name: &str) -> &'static [u8] {
    SEQUENCES
        .iter()
        .find(|(known, _)| *known == name)
        .map(|(_, letters)| letters.as_bytes())
        .expect("a probe sequence")
}

/// A genetic code as the rows translate with it.
fn code(id: u8) -> DisplayCode {
    DisplayCode::new(
        &crate::utils::genetic_code::GeneticCode::try_from_id(id).expect("a genetic code"),
    )
}

/// A probe's sequences: the nucleotide query and the subjects (`Subject_N`, or a database's OIDs), the
/// query's masks with their frames and the genetic codes of the query and of the subjects.
struct Probe {
    query: &'static [u8],
    subjects: Vec<(&'static [u8], String)>,
    query_masks: Vec<Mask>,
    query_code: DisplayCode,
    subject_code: DisplayCode,
}

impl Sequences for Probe {
    fn letters(&self, seq: SeqKey, from: u32, to: u32, out: &mut Vec<u8>) {
        let letters = match seq {
            SeqKey::Query => self.query,
            SeqKey::Subject(index) => self.subjects[index as usize].0,
        };
        out.extend_from_slice(&letters[from as usize..=to as usize]);
    }

    fn label(&self, seq: SeqKey, out: &mut Vec<u8>) {
        out.extend_from_slice(match seq {
            SeqKey::Query => b"Query_1",
            SeqKey::Subject(index) => self.subjects[index as usize].1.as_bytes(),
        });
    }

    fn masks(&self, seq: SeqKey, out: &mut Vec<Mask>) {
        if seq == SeqKey::Query {
            out.extend_from_slice(&self.query_masks);
        }
    }

    fn genetic_code(&self, master: bool) -> Option<DisplayCode> {
        Some(if master {
            self.query_code
        } else {
            self.subject_code
        })
    }
}

/// The section of the HSPs `rows` (subject index, qstart, qend, sstart, send, the query's and the
/// subject's frames in their records, BTOP) in format `format`: BLASTX's (`tblastx` false: protein
/// subjects) or TBLASTX's.
fn section(
    probe: &Probe,
    rows: &[(u32, u32, u32, u32, u32, i8, i8, &str)],
    tblastx: bool,
    format: u8,
    line_length: usize,
) -> String {
    let mut hsps = if tblastx {
        Hsps::of_translated_nucleotides()
    } else {
        Hsps::of_translated_query()
    };
    let mut segments = Segments::default();
    for &(subject, qstart, qend, sstart, send, qframe, sframe, btop) in rows {
        let hit = hit(
            qstart,
            qend,
            sstart,
            send,
            i32::from(qframe),
            ops_of_btop(btop, false),
        );
        let query = Some((qframe, probe.query.len()));
        let subject_row = tblastx.then(|| (sframe, probe.subjects[subject as usize].0.len()));
        let strands = crate::report::serial::seqalign::translated_row_segments(
            &hit,
            query,
            subject_row,
            &mut segments,
        );
        hsps.push_dense_seg(subject, segments.starts(), segments.lens(), 0, 0, strands);
    }
    let view = View {
        identity: matches!(format, 1 | 3),
        anchored: matches!(format, 1 | 2),
        html: false,
    };
    let mut out = Vec::new();
    write_section(&mut out, view, line_length, &hsps, probe).expect("the section");
    String::from_utf8(out).expect("ASCII")
}

