#!/usr/bin/env python3
"""Generate LOSAT/src/core/composition_adjustment/matrix_tables.rs from NCBI's C sources.

The composition-based statistics data of the protein matrices are transcribed with the
literal texts of the C source as the Rust literals (so the doubles are the same):

- the 28 x 28 frequency ratios of `core/matrix_freq_ratios.c` (the `*_FREQRATIOS` arrays
  that `_PSIMatrixFrequencyRatiosNew` copies);
- the 20 x 20 joint probabilities and the 20 background frequencies of
  `composition_adjustment/matrix_frequency_data.c` (the `*_JOINT_PROBS` and `*_bg` arrays of
  `s_FrequencyData`).

Both files hold the same eight matrices; IDENTITY has none of them. The matrices are in the
order of `s_FrequencyData`.

Usage: gen_compo_matrix_tables.py --ncbi-src C++DIR [--check]
  --check: exit 1 when the committed file differs from what would be generated.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
TARGET = REPO / "LOSAT/src/core/composition_adjustment/matrix_tables.rs"
FREQ = "src/algo/blast/core/matrix_freq_ratios.c"
DATA = "src/algo/blast/composition_adjustment/matrix_frequency_data.c"
NUMBER = re.compile(r"-?\d+\.\d+e[-+]\d+")


def array(lines: list[str], pattern: str, rel: str, count: int) -> tuple[int, int, list[str]]:
    """The first and last line (0-based) of the C array whose declaration matches `pattern`, and its literals."""
    start = next(i for i, line in enumerate(lines) if re.search(pattern, line))
    end = next(i for i in range(start, len(lines)) if lines[i].rstrip().endswith("};"))
    body = "\n".join(lines[start:end + 1])
    body = body[body.index("=") + 1:]
    if "/*" in body:
        raise SystemExit(f"{rel}:{start + 1}: comment inside the array")
    values = NUMBER.findall(body)
    if len(values) != count or len(re.findall(r"[-\d.e+]+", body)) != count:
        raise SystemExit(f"{rel}:{start + 1}: {len(values)} literals, expected {count}")
    return start, end, values


def rust_row(values: list[str], per_line: int, indent: str) -> str:
    lines = [", ".join(values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return "[" + (",\n" + indent + " ").join(lines) + "]"


def rust_array(values: list[str], rows: int, cols: int, per_line: int) -> str:
    """The array in the layout of the C source (`per_line` literals a line); rustfmt skips it."""
    if rows == 1:
        lines = [", ".join(values[i:i + per_line]) for i in range(0, len(values), per_line)]
        return "[\n    " + ",\n    ".join(lines) + ",\n]"
    body = ",\n    ".join(rust_row(values[r * cols:(r + 1) * cols], per_line, "    ") for r in range(rows))
    return "[\n    " + body + ",\n]"


def reference(out: list[str], rel: str, lines: list[str], start: int, end: int) -> None:
    out.append(f"/// NCBI reference: c++/{rel}:{start + 1}-{end + 1}")
    out.append("/// ```c")
    for line in lines[start:start + 2]:
        out.append(f"/// {line}".rstrip())
    out.append("/// ...")
    out.append("/// ```")


def generate(src: Path) -> str:
    freq_lines = (src / FREQ).read_text().splitlines()
    data_lines = (src / DATA).read_text().splitlines()
    data_text = "\n".join(data_lines)
    table = re.search(r"s_FrequencyData\[NUM_SUPPORTED_MATRICES\] =\s*\{(.*?)\};", data_text, re.S)
    names = re.findall(r"MATRIX_DATA\((\w+)\)", table.group(1))
    if len(names) != int(re.search(r"#define NUM_SUPPORTED_MATRICES (\d+)", data_text).group(1)):
        raise SystemExit("s_FrequencyData and NUM_SUPPORTED_MATRICES disagree")
    freq_text = "\n".join(freq_lines)
    new = freq_text[freq_text.index("_PSIMatrixFrequencyRatiosNew(const char* matrix_name)"):]
    new = new[:new.index("\n}\n")]
    copied = re.findall(r"retval->data\[i\]\[j\] = (\w+)_FREQRATIOS\[i\]\[j\];", new)
    if sorted(set(copied)) != sorted(names):
        raise SystemExit(f"_PSIMatrixFrequencyRatiosNew copies {sorted(set(copied))}, s_FrequencyData has {names}")
    out = [
        "//! NCBI's composition-based statistics data of the protein matrices, generated by",
        "//! docs/evidence/losat_web_e2e/gen_compo_matrix_tables.py from",
        f"//! c++/{FREQ} and",
        f"//! c++/{DATA} (598d8ae6); do not edit by hand.",
        "//!",
        "//! The frequency ratios are 28 x 28 in NCBIstdaa order; the joint probabilities (20 x 20) and",
        "//! the background frequencies (20) are in the order of the true amino acids",
        "//! (`trueCharPositions`). The values are the C literals as written. The eight matrices are",
        "//! in the order of `s_FrequencyData`; IDENTITY has no data in either file.",
        "",
        "/// A matrix's data: the frequency ratios that `_PSIMatrixFrequencyRatiosNew` copies and the",
        "/// joint and background probabilities of its `Compo_FrequencyData`.",
        "#[derive(Debug)]",
        "pub struct CompoMatrixData {",
        "    pub name: &'static str,",
        "    pub freq_ratios: &'static [[f64; 28]; 28],",
        "    pub joint_probs: &'static [[f64; 20]; 20],",
        "    pub background: &'static [f64; 20],",
        "}",
        "",
    ]
    for name in names:
        start, end, values = array(freq_lines, rf"^static const double {name}_FREQRATIOS\[BLASTAA_SIZE\]\[BLASTAA_SIZE\] =", FREQ, 28 * 28)
        reference(out, FREQ, freq_lines, start, end)
        out.append("#[rustfmt::skip]")
        out.append(f"pub(crate) const {name}_FREQ_RATIOS: [[f64; 28]; 28] = {rust_array(values, 28, 28, 4)};")
        out.append("")
        start, end, values = array(data_lines, rf"^{name}_JOINT_PROBS\[COMPO_NUM_TRUE_AA\]\[COMPO_NUM_TRUE_AA\] =", DATA, 20 * 20)
        reference(out, DATA, data_lines, start - 1, end)
        out.append("#[rustfmt::skip]")
        out.append(f"pub(crate) const {name}_JOINT_PROBS: [[f64; 20]; 20] = {rust_array(values, 20, 20, 3)};")
        out.append("")
        start, end, values = array(data_lines, rf"^{name}_bg\[COMPO_NUM_TRUE_AA\] =", DATA, 20)
        reference(out, DATA, data_lines, start - 1, end)
        out.append("#[rustfmt::skip]")
        out.append(f"pub(crate) const {name}_BG: [f64; 20] = {rust_array(values, 1, 20, 3)};")
        out.append("")
    start = next(i for i, line in enumerate(data_lines) if line.startswith("s_FrequencyData[NUM_SUPPORTED_MATRICES]"))
    end = next(i for i in range(start, len(data_lines)) if data_lines[i].strip() == "};")
    out.append(f"/// NCBI reference: c++/{DATA}:{start}-{end + 1}")
    out.append("/// ```c")
    for line in data_lines[start - 1:start + 4]:
        out.append(f"/// {line}".rstrip())
    out.append("/// ...")
    out.append("/// ```")
    out.append(f"pub static COMPO_MATRIX_DATA: [CompoMatrixData; {len(names)}] = [")
    for name in names:
        out.append(f"    CompoMatrixData {{ name: \"{name}\", freq_ratios: &{name}_FREQ_RATIOS, "
                   f"joint_probs: &{name}_JOINT_PROBS, background: &{name}_BG }},")
    out.append("];")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ncbi-src", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = subprocess.run(["rustfmt", "+1.92.0", "--edition", "2021", "--emit", "stdout", "--quiet"],
                          input=generate(args.ncbi_src), capture_output=True, text=True, check=True).stdout
    if args.check:
        return 0 if TARGET.read_text() == text else 1
    TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
