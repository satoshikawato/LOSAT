// Probes `p0006.d.nd0` (all four views; 98 of the grid's 277 searches): an HSP of length 0 whose query row starts at
// a codon of an HSP of the query's frame +1 splits that HSP's segment at a length of 0, where NCBI BLAST+ frees
// the segment it still walks and crashed (SIGSEGV) in every such probe; one in a frame +1 gap or past the HSP, or
// at a nucleotide of another frame (a query row of its own), does not.
#[test]
fn blastx_hsp_of_length_0_at_a_codon_of_frame_plus_one_frees_the_segment() {
    let probe = Probe {
        query: b"ATGGCTAAACGTCTGGAATTCTCTGCAGGTACCGGATCC",
        subject: b"MAKRLEFSAGTG",
    };
    let frees = |zero: (u32, u32, u32, u32, i8, &str)| {
        super::section_frees(&hsps(&probe, &[(1, 30, 1, 10, 1, "10"), zero])).expect("a merge")
    };
    // Frame +1 at nucleotide 7 (a codon start inside 1-30), frame -1 from nucleotide 13 (its row (12, 11)).
    assert!(frees((7, 6, 4, 3, 1, "")));
    assert!(frees((12, 13, 4, 3, -1, "")));
    // Frame +2 at 8 (a query row of frame 2), frame +1 at 31 (past the HSP).
    assert!(!frees((8, 7, 4, 3, 2, "")));
    assert!(!frees((31, 30, 4, 3, 1, "")));
    // Without an HSP of length 0 nothing is merged.
    assert!(!super::section_frees(&hsps(&probe, &[(1, 30, 1, 10, 1, "10")])).expect("no merge"));
}

// Review 3 of T3c, D1 (the 8 differences of its seed-11 fuzz: cases r11_001 and r11_019, `-strand minus -num_descriptions 0`,
// formats 1 to 4): the first frame group holds the HSPs of length 0 alone (in f3147 below the frame +1 HSPs too), each a
// segment of length 0 of the query's row of its own frame (`x_SetSeqFrame`). `FillUnalignedRegions`
// fills a row from the end of its previous segment, the own start of a segment of length 0, so `seg` stored in `row->SetStarts()`
// at `new_start` (alnsegments.cpp:323) replaces the row's `CRef` of it. Official NCBI BLAST+ 2.17.0 exits 139 (SIGSEGV) where that
// was the last `CRef` and `m_Segments` still lists the segment (valgrind: invalid reads in `x_CreateDenseg` of a block
