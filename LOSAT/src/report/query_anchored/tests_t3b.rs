fn sequence(name: &str) -> &'static [u8] {
    SEQUENCES
        .iter()
        .find(|(known, _)| *known == name)
        .map(|(_, letters)| letters.as_bytes())
        .expect("a probe sequence")
}

/// A probe's sequences: the query and the subjects (`Subject_N`, or a database's OIDs), their masks and
/// the subjects' genetic code (TBLASTN).
struct Probe {
    query: &'static [u8],
    subjects: Vec<(&'static [u8], String)>,
    query_masks: Vec<(u32, u32)>,
    subject_masks: Vec<Vec<(u32, u32)>>,
    code: Option<crate::algorithm::tblastx::report::DisplayCode>,
}

impl Sequences for Probe {
    fn rows_match(&self, a: SeqKey, b: SeqKey) -> bool {
        super::tests::labels_match(self, a, b)
    }

    fn letters(&self, seq: SeqKey, from: u32, to: u32, out: &mut Vec<u8>) {
        let letters = match seq {
            SeqKey::Query => self.query,
            SeqKey::Subject(index) => self.subjects[index as usize].0,
        };
        out.extend(
            letters[from as usize..=to as usize]
                .iter()
                .map(u8::to_ascii_uppercase),
        );
    }

    fn label(&self, seq: SeqKey, out: &mut Vec<u8>) {
        out.extend_from_slice(match seq {
            SeqKey::Query => b"Query_1",
            SeqKey::Subject(index) => self.subjects[index as usize].1.as_bytes(),
        });
    }

    fn masks(&self, seq: SeqKey, out: &mut Vec<Mask>) {
        let masks = match seq {
            SeqKey::Query => &self.query_masks,
            SeqKey::Subject(index) => &self.subject_masks[index as usize],
        };
        out.extend(masks.iter().map(|&(from, to)| (from, to, 0)));
    }

    fn genetic_code(&self, master: bool) -> Option<crate::algorithm::tblastx::report::DisplayCode> {
        if master {
            None
        } else {
            self.code
        }
    }
}

/// The edit script of a BTOP string (`reverse`: in the minus-strand context, against the BTOP's
/// plus-strand query order).
pub(super) fn ops_of_btop(btop: &str, reverse: bool) -> Vec<GapEditOp> {
    let bytes = btop.as_bytes();
    let mut ops: Vec<GapEditOp> = Vec::new();
    let mut push = |op: GapEditOp| match (ops.last_mut(), op) {
        (Some(GapEditOp::Sub(n)), GapEditOp::Sub(m)) => *n += m,
        (Some(GapEditOp::Ins(n)), GapEditOp::Ins(m)) => *n += m,
        (Some(GapEditOp::Del(n)), GapEditOp::Del(m)) => *n += m,
        _ => ops.push(op),
    };
    let mut at = 0;
    while at < bytes.len() {
        if bytes[at].is_ascii_digit() {
            let end = at
                + bytes[at..]
                    .iter()
                    .take_while(|b| b.is_ascii_digit())
                    .count();
            push(GapEditOp::Sub(btop[at..end].parse().expect("a BTOP run")));
            at = end;
        } else {
            push(match (bytes[at], bytes[at + 1]) {
                (b'-', _) => GapEditOp::Del(1),
                (_, b'-') => GapEditOp::Ins(1),
                _ => GapEditOp::Sub(1),
            });
            at += 2;
        }
    }
    if reverse {
        ops.reverse();
    }
    ops
}

/// A hit of the report's coordinates (1-based, in the records) with the edit script of `btop`.
pub(super) fn hit(
    q_start: u32,
    q_end: u32,
    s_start: u32,
    s_end: u32,
    query_frame: i32,
    ops: Vec<GapEditOp>,
) -> Hit {
    Hit {
        identity: 0.0,
        length: 0,
        mismatch: 0,
        gapopen: 0,
        q_start: q_start as usize,
        q_end: q_end as usize,
        s_start: s_start as usize,
        s_end: s_end as usize,
        e_value: 0.0,
        bit_score: 0.0,
        num_ident: 0,
        query_frame,
        query_length: 0,
        q_idx: 0,
        s_idx: 0,
        raw_score: 0,
        sort_query_offset: 0,
        sort_query_end: 0,
        sort_subject_offset: 0,
        sort_subject_end: 0,
        has_sort_offsets: false,
        gap_info: Some(ops),
        num_positives: 0,
    }
}

/// The section of the HSPs `rows` (subject index, qstart, qend, sstart, send, sframe, BTOP) in format
/// `format`: BLASTN's (`translated` false; a minus-strand HSP has `sstart > send`) or TBLASTN's.
fn section(
    probe: &Probe,
    rows: &[(u32, u32, u32, u32, u32, i8, &str)],
    translated: bool,
    format: u8,
    line_length: usize,
) -> String {
    let mut hsps = if translated {
        Hsps::of_translated_subjects()
    } else {
        Hsps::default()
    };
    let mut segments = Segments::default();
    for &(subject, qstart, qend, sstart, send, sframe, btop) in rows {
        let strands = if translated {
            let hit = hit(qstart, qend, sstart, send, 0, ops_of_btop(btop, false));
            let length = probe.subjects[subject as usize].0.len();
            crate::report::serial::seqalign::translated_row_segments(
                &hit,
                None,
                Some((sframe, length)),
                &mut segments,
            )
        } else {
            let minus = sstart > send;
            let hit = hit(
                qstart,
                qend,
                sstart,
                send,
                if minus { -1 } else { 1 },
                ops_of_btop(btop, minus),
            );
            crate::report::serial::seqalign::nucleotide_row_segments(&hit, &mut segments)
        };
        hsps.push_dense_seg(subject, segments.starts(), segments.lens(), 0, 0, strands);
    }
    let view = View {
        identity: matches!(format, 1 | 3),
        anchored: matches!(format, 1 | 2),
        html: false,
    };
    let mut out = Vec::new();
    write_section(&mut out, view, line_length, &hsps, probe).expect("the section");
    String::from_utf8(out).expect("ASCII")
}

