#!/usr/bin/env python3
"""Writes pylosat/_options.pyi, the keyword arguments of `Search` by program.

The stubs come from `pylosat.describe`, the table that `Search` itself reads, which is the engine's
table of arguments. tests/test_search.py checks that the file is what this script writes.

    python tools/generate_option_stubs.py [--check]
"""

from __future__ import annotations

import sys
import textwrap
from pathlib import Path

import pylosat

TARGET = Path(__file__).resolve().parents[1] / "pylosat" / "_options.pyi"
TYPES = {
    "flag": "bool",
    "boolean": "bool",
    "integer": "int",
    "real": "float",
    "path": "str | os.PathLike[str]",
    "text": "str",
}


def option_type(parameter: pylosat.Parameter) -> str:
    if parameter.choices:
        return "Literal[" + ", ".join(repr(choice) for choice in parameter.choices) + "]"
    return TYPES[parameter.value_kind]


def stubs() -> str:
    lines = [
        '"""Generated by tools/generate_option_stubs.py from `pylosat.describe`. Do not edit."""',
        "",
        "import os",
        "from typing import Literal, TypedDict",
    ]
    for program in pylosat.PROGRAMS:
        lines += ["", f"class {program.capitalize()}Options(TypedDict, total=False):"]
        for parameter in pylosat.describe(program).parameters:
            lines.append(f"    {parameter.name}: {option_type(parameter)}")
            help_text = " ".join(parameter.help.split()).replace("\\", "\\\\").replace('"', "'")
            if help_text:
                lines += textwrap.wrap(
                    f'"""{help_text}"""',
                    width=96,
                    initial_indent="    ",
                    subsequent_indent="    ",
                    break_long_words=False,
                    break_on_hyphens=False,
                )
    return "\n".join(lines) + "\n"


def main() -> int:
    text = stubs()
    if "--check" in sys.argv[1:]:
        return 0 if TARGET.read_text(encoding="utf-8") == text else 1
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
