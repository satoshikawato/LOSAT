/// A probe's sequences: the nucleotide query (`Query_1`), its one database subject (shown by its OID, `0`),
/// genetic code 1 for row 0 and BLASTX's database code 0 for the others (`None`).
struct Probe {
    query: &'static [u8],
    subject: &'static [u8],
}

impl Sequences for Probe {
    fn letters(&self, seq: SeqKey, from: u32, to: u32, out: &mut Vec<u8>) {
        let letters = match seq {
            SeqKey::Query => self.query,
            SeqKey::Subject(_) => self.subject,
        };
        out.extend_from_slice(&letters[from as usize..=to as usize]);
    }

    fn label(&self, seq: SeqKey, out: &mut Vec<u8>) {
        out.extend_from_slice(match seq {
            SeqKey::Query => b"Query_1",
            SeqKey::Subject(_) => b"0",
        });
    }

    fn masks(&self, _seq: SeqKey, _out: &mut Vec<Mask>) {}

    fn genetic_code(&self, master: bool) -> Option<DisplayCode> {
        master.then(|| {
            DisplayCode::new(
                &crate::utils::genetic_code::GeneticCode::try_from_id(1).expect("genetic code 1"),
            )
        })
    }
}

/// The section's HSPs `rows` (qstart, qend, sstart, send, the query's frame in its record, BTOP; an empty
/// BTOP for an HSP of length 0) of subject 0.
fn hsps(probe: &Probe, rows: &[(u32, u32, u32, u32, i8, &str)]) -> Hsps {
    let rows: Vec<_> = rows
        .iter()
        .map(|&(qstart, qend, sstart, send, qframe, btop)| {
            (0, qstart, qend, sstart, send, qframe, btop)
        })
        .collect();
    subject_hsps(probe.query.len(), &rows)
}

/// The section's HSPs `rows` (the subject's OID, then as in `hsps`) of a query of `query_len` nucleotides.
fn subject_hsps(query_len: usize, rows: &[(u32, u32, u32, u32, u32, i8, &str)]) -> Hsps {
    let mut hsps = Hsps::of_translated_query();
    let mut segments = Segments::default();
    for &(subject, qstart, qend, sstart, send, qframe, btop) in rows {
        let hit = hit(
            qstart,
            qend,
            sstart,
            send,
            i32::from(qframe),
            ops_of_btop(btop, false),
        );
        let strands = if btop.is_empty() {
            crate::report::serial::seqalign::empty_row_segments(&hit, qframe, &mut segments)
        } else {
            crate::report::serial::seqalign::translated_row_segments(
                &hit,
                Some((qframe, query_len)),
                None,
                &mut segments,
            )
        };
        hsps.push_dense_seg(subject, segments.starts(), segments.lens(), 0, 0, strands);
    }
    hsps
}

/// The section of `rows` in format `format`, 60 letters a line.
fn section(probe: &Probe, rows: &[(u32, u32, u32, u32, i8, &str)], format: u8) -> String {
    let view = View {
        identity: matches!(format, 1 | 3),
        anchored: matches!(format, 1 | 2),
    };
    let mut out = Vec::new();
    write_section(&mut out, view, 60, &hsps(probe, rows), probe).expect("the section");
    String::from_utf8(out).expect("ASCII")
}

