//! Unit tests of the query-anchored section of BLASTX's ungapped HSPs of length 0 (line RG T3c after dev's X2g):
//! each compares `write_section` with the bytes of an NCBI BLAST+ 2.17.0 probe (`-db`, `-num_descriptions 0`,
//! `-num_threads 1`; inputs and outputs under `/home/kawato/losat-baselines/remaining-gaps-20261112/T/t3/x2g/`:
//! `in/`, `db/`, `out/ncbi/<id>.out`). The HSPs are those of the probe's `-outfmt "6 qstart qend sstart send
//! qframe btop length"` (NCBI's bytes with `-db`), made into Dense-segs by the report's owners
//! (`seqalign::translated_row_segments`; `seqalign::empty_row_segments` for an HSP of length 0, empty BTOP
//! here). Generated by `T/t3/scripts_t3c/gen_unit_tests_x2g.py`.

