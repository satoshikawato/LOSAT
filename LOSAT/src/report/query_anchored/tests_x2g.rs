fn blastx_fill_at_a_start_that_its_row_still_holds_elsewhere_frees_nothing() {
    let hsps = subject_hsps(53, &[(0, 7, 48, 27, 42, 1, "3-KA--K5A--K-K4")]);
    assert!(matches!(super::aln_mix::merge(&hsps, &[0]), Ok(Some(_))));
}
